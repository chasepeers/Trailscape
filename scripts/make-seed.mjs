// Builds seed/stays.sql from the site's own data, so the database holds the same stays,
// beds and prices the site shows. Run: node scripts/make-seed.mjs
// Rows are upserted, so running the SQL again refreshes names and estimates but keeps real rates
// (price_estimated = 0) and engine IDs that were entered by hand.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const root = new URL("../", import.meta.url);
const read = f => readFileSync(new URL(f, root), "utf8");

// PLACES (trail packages and named stays) from app-core.js, and OPS for operator names.
const core = read("app-core.js");
// The literal that follows `start` (which ends with its opening bracket), found by bracket matching.
function slice(start) {
  const open = core.indexOf(start) + start.length - 1;
  if (open < start.length - 1) throw new Error("Not found in app-core.js: " + start);
  let depth = 0;
  for (let j = open; j < core.length; j++) {
    const c = core[j];
    if (c === "[" || c === "{") depth++;
    else if ((c === "]" || c === "}") && --depth === 0) return core.slice(open, j + 1);
  }
  throw new Error("Unbalanced literal after " + start);
}
const PLACES = vm.runInNewContext("(" + slice("const PLACES = [") + ")");
const OPS = vm.runInNewContext("(" + slice("const OPS = {") + ")");

// STAYS from stays-data.js (it builds STAYS from an embedded CSV).
const ctx = {}; vm.runInNewContext(read("stays-data.js").replace(/^const STAYS\b/m, "this.STAYS").replace(/^const STAYS_CSV\b/m, "this.STAYS_CSV"), ctx);
const STAYS = ctx.STAYS;
if (!Array.isArray(PLACES) || !Array.isArray(STAYS)) throw new Error("Could not read PLACES or STAYS");

// Same estimates as booking.js (priceOf, bedsOf), so server prices match the site's "est." prices.
const PRICE_EST = [[/luxury/i, 4500], [/lodge|resort|game reserve/i, 950], [/glamping|treehouse|tent|pod|eco-cabin/i, 650], [/backpack|dormitory/i, 280],
  [/hut|shelter|shack/i, 220], [/camp/i, 160], [/cottage|chalet|cabin|house|self-catering|farm|guest|rondavel|loft|villa|barn|venue|boat/i, 480]];
const priceOf = s => { const t = s.type.split("/")[0]; const hit = PRICE_EST.find(([re]) => re.test(t)); return hit ? hit[1] : 400; };
function bedsOf(s) {
  const t = `${s.notes} ${s.name}`;
  const m = t.match(/sleeps\s*(\d+)/i) || t.match(/up to\s*(\d+)/i) || t.match(/(\d+)\s*(?:beds|people)/i);
  if (m) return Math.max(2, +m[1]);
  const ty = s.type.toLowerCase();
  if (/camp/.test(ty) && !/cottage|chalet|cabin/.test(ty.split("/")[0])) return 40;
  if (/hut|shelter/.test(ty)) return 12;
  if (/lodge|resort|backpack|reserve|venue/.test(ty)) return 24;
  if (/glamp|tent|pod/.test(ty)) return 10;
  return 8;
}
// Two ways to book, same rule as bookMode() in app-core.js: CapeNature, SANParks and NightsBridge stays are instant
// bookings (we book into the provider's calendar); everything else is Easy enquire ("enquiry").
const NIGHTSBRIDGE = new Set(vm.runInNewContext("(" + slice("const NIGHTSBRIDGE = new Set([").replace(/,\s*\.\.\.[\s\S]*\]$/, "]") + ")"));
const modeOf = (op, id) => op === "cn" || op === "sp" || NIGHTSBRIDGE.has(id) ? "instant" : "enquiry";
const engineOf = (op, id) => op === "cn" ? "CapeNature portal" : op === "sp" ? "SANParks reservations" : NIGHTSBRIDGE.has(id) ? "NightsBridge" : null;

const q = v => v === null || v === undefined || v === "" ? "NULL" : typeof v === "number" ? String(v) : "'" + String(v).replace(/'/g, "''") + "'";
const rows = [];
for (const p of PLACES) {
  const fixed = p.nights > 1 && /trail|route|slackpack/i.test(p.kind) ? p.nights : 0;
  rows.push({ id: p.id, name: p.name, operator: OPS[p.op].label, op_key: p.op, kind: p.kind, mode: modeOf(p.op, p.id),
    fixed_nights: fixed, beds: p.beds, price_pp: p.price, price_estimated: 0, engine: engineOf(p.op, p.id), booking_email: null, booking_phone: null });
}
const seen = new Set(rows.map(r => r.id));
for (const s of STAYS) {
  if (!s.id || seen.has(s.id)) continue; seen.add(s.id);
  rows.push({ id: s.id, name: s.name, operator: s.operator, op_key: s.k, kind: s.type, mode: modeOf(s.k, s.id), fixed_nights: 0,
    beds: bedsOf(s), price_pp: priceOf(s), price_estimated: 1, engine: engineOf(s.k, s.id),
    booking_email: (s.email || "").split(/[ ,;/]+/)[0] || null, booking_phone: (s.phones[0] || [])[1] || null });
}

const cols = ["id", "name", "operator", "op_key", "kind", "mode", "fixed_nights", "beds", "price_pp", "price_estimated", "engine", "booking_email", "booking_phone"];
const sql = [`-- Generated by scripts/make-seed.mjs on ${new Date().toISOString().slice(0, 10)} from app-core.js and stays-data.js (${rows.length} stays).`];
for (let i = 0; i < rows.length; i += 40) {
  sql.push(`INSERT INTO stays (${cols.join(", ")}) VALUES\n` + rows.slice(i, i + 40).map(r => "  (" + cols.map(c => q(r[c])).join(", ") + ")").join(",\n") +
    `\nON CONFLICT(id) DO UPDATE SET name = excluded.name, operator = excluded.operator, op_key = excluded.op_key, kind = excluded.kind,
  mode = excluded.mode, engine = COALESCE(excluded.engine, stays.engine),
  fixed_nights = excluded.fixed_nights, beds = excluded.beds,
  price_pp = CASE WHEN stays.price_estimated = 1 THEN excluded.price_pp ELSE stays.price_pp END,
  booking_email = COALESCE(stays.booking_email, excluded.booking_email), booking_phone = COALESCE(stays.booking_phone, excluded.booking_phone),
  updated_at = strftime('%Y-%m-%dT%H:%M:%SZ', 'now');`);
}
writeFileSync(new URL("seed/stays.sql", root), sql.join("\n\n") + "\n");
console.log(`${rows.length} stays (${PLACES.length} packages/named stays, ${rows.length - PLACES.length} listings, ${rows.filter(r => r.mode === "instant").length} instant)`);
